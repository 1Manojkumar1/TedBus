@Injectable({
  providedIn: 'root',
})
export class TranslationService {
  readonly supportedLanguages = SUPPORTED_LANGUAGES;

  private readonly langSignal = signal<SupportedLanguage>(this.detectInitialLanguage());

  readonly currentLanguage = computed(() => this.langSignal());

  private detectInitialLanguage(): SupportedLanguage {
    try {
      const stored = localStorage.getItem(LANG_STORAGE_KEY) as SupportedLanguage | null;
      if (stored && SUPPORTED_LANGUAGES.some((l) => l.code === stored)) {
        return stored;
      }
      const browserLang = (navigator.language || '').slice(0, 2).toLowerCase();
      const match = SUPPORTED_LANGUAGES.find((l) => l.code === browserLang);
      if (match) return match.code;
    } catch {
      // ignore SSR or storage exceptions
    }
    return 'en';
  }

  setLanguage(lang: SupportedLanguage): void {
    if (!SUPPORTED_LANGUAGES.some((l) => l.code === lang)) return;
    this.langSignal.set(lang);
    try {
      localStorage.setItem(LANG_STORAGE_KEY, lang);
      document.documentElement.lang = lang;
    } catch {}
  }

  translate(key: string, params?: Record<string, string | number>): string {
    const lang = this.langSignal();
    const dict = DICTIONARIES[lang] || DICTIONARIES.en;
    let text = dict[key] || DICTIONARIES.en[key] || key;

    if (params) {
      for (const [k, v] of Object.entries(params)) {
        text = text.replace(new RegExp(`{\\s*${k}\\s*}`, 'g'), String(v));
      }
    }
    return text;
  }

  instant(key: string, params?: Record<string, string | number>): string {
    return this.translate(key, params);
  }
}
