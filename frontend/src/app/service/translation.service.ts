@Injectable({
  providedIn: 'root',
})
export class TranslationService {
  readonly currentLanguage = signal<SupportedLanguage>(this.getInitialLanguage());
  readonly supportedLanguages = SUPPORTED_LANGUAGES;

  readonly activeDictionary = computed(() => {
    const lang = this.currentLanguage();
    return DICTIONARIES[lang] || DICTIONARIES.en;
  });

  setLanguage(lang: SupportedLanguage): void {
    if (DICTIONARIES[lang]) {
      this.currentLanguage.set(lang);
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem(LANG_STORAGE_KEY, lang);
      }
      if (typeof document !== 'undefined') {
        document.documentElement.lang = lang;
      }
    }
  }

  translate(key: string, params?: Record<string, string | number>): string {
    const dict = this.activeDictionary();
    let text = dict[key] || DICTIONARIES.en[key] || key;

    if (params) {
      for (const [paramKey, paramValue] of Object.entries(params)) {
        text = text.replace(new RegExp(`{{${paramKey}}}`, 'g'), String(paramValue));
      }
    }

    return text;
  }

  private getInitialLanguage(): SupportedLanguage {
    if (typeof localStorage !== 'undefined') {
      const stored = localStorage.getItem(LANG_STORAGE_KEY) as SupportedLanguage | null;
      if (stored && DICTIONARIES[stored]) {
        return stored;
      }
    }
    return 'en';
  }
}
